"""Exhaustive small-instance checks of the manuscript's algebraic claims."""
import itertools
import json
import random
from pathlib import Path


def vectors(q, n):
    return itertools.product(range(q), repeat=n)


def lee(x, q):
    return sum(min(a, q-a) for a in x)


def generated(g, q):
    return {tuple(sum(u[j]*g[j][k] for j in range(len(g))) % q
                  for k in range(len(g[0]))) for u in vectors(q, len(g))}


def rank_chain(matrix, p, r):
    if not matrix or not matrix[0] or r == 0:
        return 0
    modulus = p**r
    a = [[x % modulus for x in row] for row in matrix]
    pivot = next(((i, j) for i, row in enumerate(a) for j, x in enumerate(row)
                  if x % p), None)
    if pivot is None:
        return rank_chain([[x//p for x in row] for row in a], p, r-1)
    i, j = pivot
    a[0], a[i] = a[i], a[0]
    for row in a:
        row[0], row[j] = row[j], row[0]
    inv = pow(a[0][0], -1, modulus)
    a[0] = [x*inv % modulus for x in a[0]]
    for row in a[1:]:
        factor = row[0]
        for c in range(len(row)):
            row[c] = (row[c]-factor*a[0][c]) % modulus
    return 1+rank_chain([row[1:] for row in a[1:]], p, r)


def mul_extension(x, y, modulus, degree=3):
    # Polynomial basis of Z_modulus[X]/(X^3+X+1).
    out = [0]*(2*degree-1)
    for i, a in enumerate(x):
        for j, b in enumerate(y):
            out[i+j] += a*b
    for i in range(len(out)-1, degree-1, -1):
        out[i-degree] -= out[i]
        out[i-degree+1] -= out[i]
    return tuple(x % modulus for x in out[:degree])


def main():
    rng = random.Random(22092026)
    checks = 0
    for p, r, n in ((2, 3, 3), (3, 2, 2)):
        q = p**r
        ambient = list(vectors(q, n))
        for _ in range(8):
            g = [rng.choice(ambient), rng.choice(ambient)]
            code = generated(g, q)
            for i in range(r):
                scale = p**i
                ds = {tuple(x % p for x in v) for v in ambient
                      if tuple(scale*x % q for x in v) in code}
                next_code = {tuple(x % (p*scale) for x in c) for c in code}
                for _ in range(8):
                    c, e = rng.choice(list(code)), rng.choice(ambient)
                    y = tuple((a+b) % q for a, b in zip(c, e))
                    low = tuple(x % scale for x in e)
                    digit = tuple((x//scale) % p for x in e)
                    actual = {z for z in vectors(p, n)
                              if tuple((a-b-scale*d) % (p*scale)
                                       for a, b, d in zip(y, low, z)) in next_code}
                    expected = {tuple((a+b) % p for a, b in zip(digit, d)) for d in ds}
                    assert actual == expected
                    checks += 1
    lee_checks = 0
    for p, r in ((2, 3), (3, 2), (5, 2)):
        for a in range(1, r+1):
            for x in range(p**a):
                minimum = min(lee((x+p**a*z,), p**r) for z in range(p**(r-a)))
                assert minimum == lee((x,), p**a)
                lee_checks += 1
    code = generated([(1, 3)], 9)
    y, t = (1, 0), 1
    distance = min(lee(c, 9) for c in code if any(c))
    full = [e for e in vectors(9, 2) if lee(e, 9) <= t and
            tuple((a-b) % 9 for a, b in zip(y, e)) in code]
    residue = {tuple(x % 3 for x in c) for c in code}
    prefixes = [e for e in vectors(3, 2) if lee(e, 3) <= t and
                tuple((a-b) % 3 for a, b in zip(y, e)) in residue]
    assert distance == 3 and full == [(1, 0)] and len(prefixes) == 3
    # Rank-one vector over GR(4,2), in basis (1,alpha).
    matrix = [[1, 3], [2, 2]]
    assert rank_chain(matrix, 2, 2) == 1
    assert rank_chain([[0, 1], [1, 1]], 2, 1) == 2
    # Rank-three repetition-like S-linear code generated by (1,alpha,alpha^2).
    elems = list(vectors(4, 3))
    basis = [(1, 0, 0), (0, 1, 0), (0, 0, 1)]
    rank_code = [tuple(mul_extension(u, b, 4) for b in basis) for u in elems]
    rank_vec = lambda x, r: rank_chain([list(row) for row in zip(*x)], 2, r)
    rd = min(rank_vec(c, 2) for c in rank_code if any(any(a) for a in c))
    assert rd == 3
    for a in (1, 2):
        reduced = {tuple(tuple(t % 2**a for t in v) for v in c) for c in rank_code}
        assert min(rank_vec(c, a) for c in reduced if any(any(v) for v in c)) >= rd
    rank_prefix_checks = 0
    for _ in range(12):
        u = rng.choice([x for x in elems if any(v % 2 for v in x)])
        coeff = [rng.randrange(4) for _ in range(3)]
        error = tuple(tuple(k*v % 4 for v in u) for k in coeff)
        c = rng.choice(rank_code)
        y = tuple(tuple((x+z) % 4 for x, z in zip(a, b)) for a, b in zip(c, error))
        for a in (1, 2):
            modulus = 2**a
            candidates = {tuple(tuple((x-z) % modulus for x, z in zip(v, w))
                                for v, w in zip(y, c)) for c in rank_code}
            valid = {v for v in candidates if rank_vec(v, a) <= 1}
            expected = tuple(tuple(x % modulus for x in v) for v in error)
            assert valid == {expected}
            rank_prefix_checks += 1
    result = {'affine_fiber_checks': checks, 'lee_minimum_completion_checks': lee_checks,
              'lee_counterexample': {'distance': distance, 'full_solutions': full,
                                     'prefix_solutions': prefixes},
              'rank_digit_counterexample': {'ring_rank': 1, 'second_digit_rank': 2},
              'rank_code_distance': rd, 'rank_prefix_checks': rank_prefix_checks}
    Path('theory_verification.json').write_text(json.dumps(result, indent=2), encoding='utf-8')
    print(json.dumps(result, indent=2))


if __name__ == '__main__':
    main()
